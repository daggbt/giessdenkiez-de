import { createClient } from "@supabase/supabase-js";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { CouncilId } from "../../src/config/councils";
import type { ImportReport, TreeRecord } from "./normalise";

// Per council's file. The City of Cockburn's 76,000 trees are about 19 MB,
// which Vercel serves compressed at about 1 MB, but browsers still parse all
// of it.
export const MAX_GEOJSON_BYTES = 25 * 1024 * 1024;
const SEED_BATCH_SIZE = 1000;
const PUSH_BATCH_SIZE = 500;

const round6 = (n: number) => Math.round(n * 1e6) / 1e6;

function ensureDir(file: string) {
	mkdirSync(dirname(file), { recursive: true });
}

export function buildGeoJson(records: TreeRecord[]): string {
	const features = records.map((r) =>
		JSON.stringify({
			type: "Feature",
			geometry: { type: "Point", coordinates: [round6(r.lng), round6(r.lat)] },
			properties: {
				id: r.id,
				council: r.council,
				genus: r.genus,
				common_name: r.common_name,
				planted_date: r.planted_date,
				planted_date_precision: r.planted_date_precision,
			},
		}),
	);
	// One feature per line keeps diffs of the committed file readable.
	return `{"type":"FeatureCollection","features":[\n${features.join(",\n")}\n]}\n`;
}

/**
 * Writes `<dir>/<council>.geojson` for each council: the map loads a council's
 * trees when it gets there. Checks every file's size before writing any.
 */
export function writeCouncilGeoJson(
	recordsByCouncil: Array<[CouncilId, TreeRecord[]]>,
	dir: string,
): Array<{ file: string; bytes: number }> {
	const files = recordsByCouncil.map(([council, records]) => {
		const file = join(dir, `${council}.geojson`);
		const content = buildGeoJson(records);
		const bytes = Buffer.byteLength(content);
		if (bytes > MAX_GEOJSON_BYTES) {
			throw new Error(
				`${file} would be ${(bytes / 1024 / 1024).toFixed(1)} MB, above the ${MAX_GEOJSON_BYTES / 1024 / 1024} MB limit.`,
			);
		}
		return { file, content, bytes };
	});
	mkdirSync(dir, { recursive: true });
	for (const { file, content } of files) {
		writeFileSync(file, content);
	}
	return files.map(({ file, bytes }) => ({ file, bytes }));
}

const COLUMNS = [
	"id",
	"council",
	"source_object_id",
	"botanical_name",
	"common_name",
	"family",
	"genus",
	"planted_date",
	"planted_date_precision",
	"suburb",
	"height_m",
	"is_rare",
	"is_heritage",
	"is_significant",
	"is_significant_group",
	"lat",
	"lng",
] as const satisfies ReadonlyArray<keyof TreeRecord>;

export function sqlLiteral(value: string | number | boolean | null): string {
	if (value === null) {
		return "null";
	}
	if (typeof value === "number") {
		return String(value);
	}
	if (typeof value === "boolean") {
		return value ? "true" : "false";
	}
	return `'${value.replace(/'/g, "''")}'`;
}

export function buildSeedSql(records: TreeRecord[]): string {
	const updates = COLUMNS.filter((c) => c !== "id")
		.map((c) => `${c} = excluded.${c}`)
		.concat("imported_at = now()")
		.join(", ");

	const statements: string[] = [];
	for (let i = 0; i < records.length; i += SEED_BATCH_SIZE) {
		const rows = records
			.slice(i, i + SEED_BATCH_SIZE)
			.map((r) => `(${COLUMNS.map((c) => sqlLiteral(r[c])).join(", ")})`);
		statements.push(
			`insert into public.trees (${COLUMNS.join(", ")}) values\n${rows.join(",\n")}\n` +
				`on conflict (id) do update set ${updates};\n`,
		);
	}

	return (
		"-- Generated by `npm run import:trees` from the councils' tree inventories.\n" +
		"-- Generated file - do not edit.\n\n" +
		statements.join("\n")
	);
}

export function writeSeedSql(records: TreeRecord[], file: string) {
	ensureDir(file);
	writeFileSync(file, buildSeedSql(records));
}

export function writeReport(reports: ImportReport[], file: string) {
	ensureDir(file);
	writeFileSync(file, `${JSON.stringify(reports, null, 2)}\n`);
}

export function printSummary(report: ImportReport) {
	const lines = [
		`Council:            ${report.council}`,
		`Fetched:            ${report.totalFetched}`,
		`Kept:               ${report.kept}`,
		`Skipped:            ${JSON.stringify(report.skipped)}`,
		`Duplicate IDs:      ${report.duplicateIds}`,
		`By date precision:  ${JSON.stringify(report.byPrecision)}`,
		"By suburb:",
		...Object.entries(report.bySuburb).map(([s, n]) => `  ${s}: ${n}`),
		"Top genera:",
		...report.topGenera.map((g) => `  ${g.genus}: ${g.count}`),
		`Discarded genus values: ${JSON.stringify(report.discardedGenusValues)}`,
		`Bounding box:       ${report.bbox?.join(",")}`,
		`Centre:             ${report.center?.lng}, ${report.center?.lat}`,
	];
	if (report.outsideConfiguredBbox > 0) {
		lines.push(
			`WARNING: ${report.outsideConfiguredBbox} trees are outside the council's bbox in src/config/councils.ts. ` +
				"Put the bounding box above there, or the map may not reach them.",
		);
	}
	console.log(lines.join("\n"));
}

/** Upserts the records using the service-role key. Never exposed to the browser. */
export async function pushToSupabase(
	records: TreeRecord[],
	url: string,
	serviceRoleKey: string,
) {
	const supabase = createClient(url, serviceRoleKey, {
		auth: { persistSession: false, autoRefreshToken: false },
	});
	const importedAt = new Date().toISOString();

	for (let i = 0; i < records.length; i += PUSH_BATCH_SIZE) {
		const batch = records
			.slice(i, i + PUSH_BATCH_SIZE)
			.map((r) => ({ ...r, imported_at: importedAt }));
		const { error } = await supabase
			.from("trees")
			.upsert(batch, { onConflict: "id" });
		if (error) {
			throw new Error(`Upsert failed at row ${i}: ${error.message}`);
		}
		console.log(
			`Pushed ${Math.min(i + PUSH_BATCH_SIZE, records.length)} / ${records.length}`,
		);
	}
}
